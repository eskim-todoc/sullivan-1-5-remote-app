const {chromium}=require('C:/Users/EUNSU/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const {pathToFileURL}=require('node:url');
const fs=require('node:fs');
const path=require('node:path');
(async()=>{
 const target=path.join(__dirname,'preview','portrait');
 const browser=await chromium.launch({headless:true,executablePath:'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe'});
 const context=await browser.newContext({viewport:{width:1280,height:1000},deviceScaleFactor:1});
 const page=await context.newPage(),errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 await page.goto(pathToFileURL(path.join(target,'boards.html')).href);
 await page.evaluate(()=>document.fonts.ready);
 await page.locator('#overview').screenshot({path:path.join(target,'screens','overview.png')});
 await page.locator('#management').screenshot({path:path.join(target,'screens','management-flow.png')});
 await page.goto(pathToFileURL(path.join(target,'index.html')).href);
 await page.evaluate(()=>document.fonts.ready);
 await page.screenshot({path:path.join(target,'screens','gallery.png'),fullPage:true});
 const images=await page.locator('img').evaluateAll(items=>items.map(e=>({src:e.getAttribute('src'),loaded:e.complete&&e.naturalWidth>0})));
 const wideOverflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
 await page.selectOption('#screen','logs');
 await page.frameLocator('#live').locator('#log-query').waitFor();
 const liveLogs=await page.frameLocator('#live').locator('#log-query').count()===1;
 await page.selectOption('#fw','46');
 await page.selectOption('#screen','ff');
 await page.frames().find(frame=>frame!==page.mainFrame()).waitForURL(/page=ff.*fw=46/);
 await page.frameLocator('#live').getByText('R4.6',{exact:true}).first().waitFor();
 const liveFf=await page.frameLocator('#live').locator('body').innerText();
 await page.setViewportSize({width:390,height:844});
 const narrowOverflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
 const result={errors,images,wideOverflow,narrowOverflow,liveLogs,liveFf:liveFf.includes('FF')};
 fs.writeFileSync(path.join(__dirname,'portrait-gallery-validation.json'),JSON.stringify(result,null,2));
 console.log(JSON.stringify(result,null,2));
 await context.close();await browser.close();
})().catch(e=>{console.error(e);process.exit(1);});
